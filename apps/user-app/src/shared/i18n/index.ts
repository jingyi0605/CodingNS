function withShellOverrides(
  source: Record<string, unknown>,
  shellOverrides: Record<string, unknown>
): Record<string, unknown> {
  const sourceShell = source["shell"];

  return {
    ...source,
    shell: {
      ...(sourceShell && typeof sourceShell === "object"
        ? (sourceShell as Record<string, unknown>)
        : {}),
      ...shellOverrides
    }
  };
}

const extensionDictionaries: Record<AppLanguage, Record<string, unknown>> = {
  "zh-CN": withShellOverrides(extensionZhCN, butlerInitCopyOverridesZhCN),
  "en-US": withShellOverrides(extensionEnUS, butlerInitCopyOverridesEnUS)
};

function readValue(key: string, source: DictionaryValue): string {
  const path = key.split(".");
  let current: DictionaryValue | undefined = source;

  for (const segment of path) {
    if (!current || typeof current === "string") {
      return key;
    }

    const nextValue = current[segment];

    if (nextValue === undefined || nextValue === null) {
      return key;
    }

    current = nextValue as DictionaryValue;
  }

  return typeof current === "string" ? current : key;
}

function getCurrentLanguage(): AppLanguage {
  return userPreferenceStore.getState().profile.language ?? "zh-CN";
}

export function t(key: string, params?: TranslationParams): string {
  const language = getCurrentLanguage();
  const localeCandidates: AppLanguage[] = language === "en-US" ? ["en-US", "zh-CN"] : ["zh-CN"];

  for (const locale of localeCandidates) {
    const extensionValue = readValue(key, extensionDictionaries[locale]);

    if (extensionValue !== key) {
      return interpolateTemplate(extensionValue, params);
    }

    const dictionaryValue = readValue(key, dictionaries[locale]);

    if (dictionaryValue !== key) {
      return interpolateTemplate(dictionaryValue, params);
    }
  }

  return interpolateTemplate(key, params);
}

function interpolateTemplate(template: string, params?: TranslationParams): string {
  if (!params) {
    return template;
  }

  return template.replace(/\{([^}]+)\}/g, (matched, token) => {
    const value = params[token];

    if (value === null || value === undefined) {
      return matched;
    }

    return String(value);
  });
}

interface I18nProviderProps {
  children: ReactNode;
  language: AppLanguage;
}

export function I18nProvider({ children, language }: I18nProviderProps) {
  useEffect(() => {
    document.documentElement.setAttribute("lang", language);
  }, [language]);

  return children;
}

/**
 * 响应式的翻译hook，语言切换时会自动触发组件重新渲染
 */
export function useT(): (key: string) => string {
  const language = usePreferencesSelector((state) => state.profile.language);

  return (key: string) => {
    const localeCandidates: AppLanguage[] = language === "en-US" ? ["en-US", "zh-CN"] : ["zh-CN"];

    for (const locale of localeCandidates) {
      const extensionValue = readValue(key, extensionDictionaries[locale]);

      if (extensionValue !== key) {
        return extensionValue;
      }

      const dictionaryValue = readValue(key, dictionaries[locale]);

      if (dictionaryValue !== key) {
        return dictionaryValue;
      }
    }

    return key;
  };
}

